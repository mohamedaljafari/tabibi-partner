/**
 * خدمات التخصص المختار، أو خدمات "أخرى" إذا لم يكن التخصص في القائمة.
 */
export function getServicesForSpecialization(specialization: string): string[] {
  return SPECIALIZATION_SERVICES[specialization] ?? SPECIALIZATION_SERVICES["أخرى"];
}

export type ServicesValidation = {
  services: string;
  customServices: string;
};

export function validateProviderServices(services: ProviderService[]): ServicesValidation {
  const invalid = services
    .filter((service) => service.isCustom !== true)
    .find(
      (service) =>
        typeof service.price !== "number" ||
        service.price < 0 ||
        (typeof service.durationMinutes === "number" && service.durationMinutes < 5),
    );
  const customInvalid = services
    .filter((service) => service.isCustom === true)
    .find(
      (service) =>
        !service.name.trim() ||
        typeof service.price !== "number" ||
        service.price < 0 ||
        (typeof service.durationMinutes === "number" && service.durationMinutes < 5),
    );
  return {
    services: invalid ? "حدد سعرًا صحيحًا لكل خدمة مختارة (0 أو أعلى)، ومدة لا تقل عن 5 دقائق إذا حُدّدت" : "",
    customServices: customInvalid ? "كل خدمة مضافة يجب أن تحمل اسمًا وسعرًا صحيحًا، ومدة لا تقل عن 5 دقائق إذا حُدّدت" : "",
  };
}

export function hasServicesErrors(errors: ServicesValidation): boolean {
  return errors.services.length > 0 || errors.customServices.length > 0;
}

export type AvailabilityValidation = {
  availability: string;
};

/**
 * التحقق من أن كل موعدة في الجدول تبدأ قبل أن تنتهي.
 */
export function validateAvailability(availability: ProviderAvailability): AvailabilityValidation {
  for (const slot of availability.slots) {
    if (slot.startHour >= slot.endHour) {
      return { availability: `موعد ${WEEKDAYS.find((day) => day.key === slot.day)?.label} غير صالح: بداية الموعد يجب أن تسبق نهايته` };
    }
  }
  return { availability: "" };
}

export function hasAvailabilityErrors(errors: AvailabilityValidation): boolean {
  return errors.availability.length > 0;
}
